"""Step 1 of the image build: vector pages + word boxes from the real SEC order PDF.

Writes into src/pages/, for the pages the figures show (1, 4, 8, 9, 10, 11):
  sec_pNN.svg     the page of docs/sec_order_2017_33-10280.pdf as vector SVG (glyphs as paths,
                  transparent background, 612 x 792 pt), so the HTML figures stay sharp at any size
  sec_words.js    every word on those pages with its box in PDF points, its baseline and font size,
                  footnote superscripts split off as their own words (sup: 1)
The HTML figures look phrases up in sec_words.js, so every marker sits on the document's own words,
and a phrase that is not on the page word for word stops the render. These files (about 2.4 MB) are not
kept in git: they are rebuilt exactly from the PDF (PyMuPDF 1.28: pip install pymupdf pillow).

The patent figure uses pages/patent_front.png: the top of the front page of US 7,587,347 B2
(the scan in docs/patents/US7587347.pdf, page 1; rebuilt from it when the file is missing).
It has no text layer; measure_patent.py prints the ink boxes that patent_front.html and
sec_collage.html use.

Run:  python build_pages.py   then   node render.js   (from this folder)

Pixel-identical output needs the Windows fonts Segoe UI (doc.css) and Times New Roman (figures/figures.css);
elsewhere captions and quotes fall back to system-ui and to Tinos or Liberation Serif.
"""
import json
import os
import sys

import pymupdf

HERE = os.path.dirname(os.path.abspath(__file__))
DOCS = os.path.normpath(os.path.join(HERE, '..', '..'))
PDF = os.path.join(DOCS, 'sec_order_2017_33-10280.pdf')
PATENT = os.path.join(DOCS, 'patents', 'US7587347.pdf')
OUT = os.path.join(HERE, 'pages')
PAGES = [1, 4, 8, 9, 10, 11]          # the pages the figures show
LEAD = '(“‘"\'['            # punctuation a box may leave out at the start of a word
TRAIL = ',.;:)”’"\']'       # ... and at the end


def words_from_page(page):
    """Words with char-exact boxes. A change of font size inside a run (footnote marks) starts a new word."""
    raw = page.get_text('rawdict')
    out = []
    line_id = 0
    for b in raw['blocks']:
        for ln in b.get('lines', []):
            line_id += 1
            spans = ln['spans']
            if not spans:
                continue
            main = max(s['size'] for s in spans)
            cur = None
            for s in spans:
                size = s['size']
                sup = 1 if size < main * 0.8 else 0
                for ch in s['chars']:
                    c = ch['c']
                    if c.isspace():
                        if cur:
                            out.append(cur)
                            cur = None
                        continue
                    x0, y0, x1, y1 = ch['bbox']
                    if cur and (cur['sup'] != sup):
                        out.append(cur)
                        cur = None
                    if cur is None:
                        cur = {'t': '', 'x0': x0, 'y0': y0, 'x1': x1, 'y1': y1,
                               'base': s['origin'][1], 'size': size, 'sup': sup,
                               'line': line_id, 'bold': 1 if (s['flags'] & 16) else 0, 'cx': []}
                    cur['t'] += c
                    cur['cx'].append((x0, x1))
                    cur['x0'] = min(cur['x0'], x0)
                    cur['y0'] = min(cur['y0'], y0)
                    cur['x1'] = max(cur['x1'], x1)
                    cur['y1'] = max(cur['y1'], y1)
            if cur:
                out.append(cur)
    for w in out:
        # core = the word without leading / trailing punctuation, for tight red boxes
        t, cx = w['t'], w.pop('cx')
        a, b = 0, len(t)
        while a < b - 1 and t[a] in LEAD:
            a += 1
        while b > a + 1 and t[b - 1] in TRAIL:
            b -= 1
        w['core'] = t[a:b]
        w['cx0'], w['cx1'] = cx[a][0], cx[b - 1][1]
        for k in ('x0', 'y0', 'x1', 'y1', 'base', 'size', 'cx0', 'cx1'):
            w[k] = round(w[k], 2)
    return out


def main():
    os.makedirs(OUT, exist_ok=True)
    doc = pymupdf.open(PDF)
    words = {}
    for n in PAGES:
        page = doc[n - 1]
        svg = page.get_svg_image(matrix=pymupdf.Identity, text_as_path=True)
        with open(os.path.join(OUT, 'sec_p%02d.svg' % n), 'w', encoding='utf-8') as f:
            f.write(svg)
        words[n] = words_from_page(page)
    with open(os.path.join(OUT, 'sec_words.js'), 'w', encoding='utf-8') as f:
        f.write('// generated by build_pages.py from docs/sec_order_2017_33-10280.pdf\n')
        f.write('window.SEC_PAGE = {w: %s, h: %s};\n' % (doc[0].rect.width, doc[0].rect.height))
        f.write('window.SEC_WORDS = ')
        json.dump(words, f, ensure_ascii=False, separators=(',', ':'))
        f.write(';\n')
    print('SEC order: %d pages exported, %d words' % (len(PAGES), sum(len(v) for v in words.values())))

    # patent front page: kept as given; rebuilt from the scan only when missing
    # (top 2046 of 3300 rows of the 2560 px wide page-1 image, scaled to 1600 px: matches the given
    # crop to a mean difference of 0.5 grey levels)
    front = os.path.join(OUT, 'patent_front.png')
    if not os.path.exists(front):
        import io
        from PIL import Image
        pat = pymupdf.open(PATENT)
        pix = pymupdf.Pixmap(pat, pat[0].get_images(full=True)[0][0])
        im = Image.open(io.BytesIO(pix.tobytes('png'))).convert('L')
        im.crop((0, 0, 2560, 2046)).resize((1600, 1278), Image.LANCZOS).save(front)
        print('patent front page rebuilt from', PATENT)


if __name__ == '__main__':
    sys.exit(main())
